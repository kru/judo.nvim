-- get a hex list of judo.nvim colors based on current bg and contrast config
local function get_colors()
	local p = Judo.palette
	local config = Judo.config

	for color, hex in pairs(config.palette_overrides) do
		p[color] = hex
	end

	local bg = vim.o.background
	local contrast = config.contrast

	local color_groups = {
		dark = {
			bg = p.bg,
			bg0 = p.dark0,
			bg1 = p.dark1,
			bg2 = p.dark2,
			bg3 = p.dark3,
			bg4 = p.dark4,
			fg = p.fg,
			fg0 = p.light0,
			fg1 = p.light1,
			fg2 = p.light2,
			fg3 = p.light3,
			fg4 = p.light4,
			red = p.red_minus1,
			green = p.green,
			yellow = p.yellow,
			blue = p.blue,
			steel_blue = p.steel_blue,
			light_blue = p.light_blue,
			orange = p.orange,
			dark_orange = p.dark_orange,
			light_orange = p.light_orange,
			brown = p.brown,
			niagara = p.niagara,
			niagara1 = p.niagara1,
			niagara2 = p.niagara2,
			wisteria = p.wisteria,
			gold = p.gold,
			pale_sand = p.pale_sand,
			gray = p.gray,
			light_gray = p.light_gray,
			ivory = p.ivory,
			teal = p.teal,
			white = p.white,
			aqua = p.aqua,
			quartz = p.quartz,
			purple = p.purple,
			neutral_red = p.neutral_red,
			neutral_green = p.neutral_green,
			neutral_yellow = p.neutral_yellow,
			neutral_blue = p.neutral_blue,
			neutral_purple = p.neutral_purple,
			neutral_aqua = p.neutral_aqua,
		}
	}

	if contrast ~= nil and contrast ~= "" then
		color_groups[bg].bg0 = p[bg .. "0_" .. contrast]
		color_groups[bg].dark_red = p[bg .. "_red_" .. contrast]
		color_groups[bg].dark_green = p[bg .. "_green_" .. contrast]
		color_groups[bg].dark_aqua = p[bg .. "_aqua_" .. contrast]
	end

	return color_groups[bg]
end

